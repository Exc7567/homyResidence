// Processes the raw POI photos in poi-assets/ into uniform 4:3 WebP files the site serves.
//   - matches each photo to a POI by folder/file name (longest alias wins; ties are not guessed)
//   - crops to 4:3 around the focal point in scripts/poi-photo-config.mjs, then resizes
//   - writes public/images/poi/<id>.webp (+ <id>-sm.webp), src/data/poiPhotos.js and a report
// Originals in poi-assets/ are only read, never modified. Usage: npm run poi:photos
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';
import { POI_CATALOG } from '../src/data/pois.js';
import { OUTPUT, POI_PHOTO_CONFIG } from './poi-photo-config.mjs';

const SRC_DIR = 'poi-assets';
const REPORT = 'update-md/poi-photo-report.md';
const IMAGE_EXT = /\.(webp|jpe?g|png|avif|heic|tiff?)$/i;
const RATIO = 4 / 3;
const HEAVY_CROP = 0.6; // report when less than 60% of the original area is kept

const compact = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, '');

const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) =>
    d.isDirectory() ? walk(path.join(dir, d.name)) : [path.join(dir, d.name)],
  );

// Best POI for one file: folder name first (more specific), then file name.
function matchFile(file) {
  const parts = [path.basename(path.dirname(file)), path.basename(file).replace(/\.[^.]+$/, '')].map(compact);
  for (const part of parts) {
    const hits = [];
    for (const [id, cfg] of Object.entries(POI_PHOTO_CONFIG)) {
      const len = Math.max(0, ...cfg.aliases.filter((a) => part.includes(a)).map((a) => a.length));
      if (len) hits.push({ id, len });
    }
    if (!hits.length) continue;
    hits.sort((a, b) => b.len - a.len);
    if (hits[1] && hits[1].len === hits[0].len && hits[1].id !== hits[0].id) {
      return { ambiguous: hits.filter((h) => h.len === hits[0].len).map((h) => h.id) };
    }
    return { id: hits[0].id };
  }
  return {};
}

// Largest 4:3 rectangle centred on the focal point, clamped inside the image.
function cropBox(w, h, focus) {
  let cw = w;
  let ch = Math.round(w / RATIO);
  if (ch > h) { ch = h; cw = Math.round(h * RATIO); }
  const fx = focus?.x ?? 0.5;
  const fy = focus?.y ?? (h > w ? 0.4 : 0.5);
  const left = Math.min(Math.max(0, Math.round(fx * w - cw / 2)), w - cw);
  const top = Math.min(Math.max(0, Math.round(fy * h - ch / 2)), h - ch);
  return { left, top, width: cw, height: ch };
}

const files = fs.existsSync(SRC_DIR) ? walk(SRC_DIR).filter((f) => IMAGE_EXT.test(f)) : [];
fs.mkdirSync(OUTPUT.dir, { recursive: true });

const matched = [];
const unmatched = [];
const duplicates = [];
const byId = new Map();

for (const file of files) {
  const m = matchFile(file);
  if (!m.id) { unmatched.push({ file, reason: m.ambiguous ? `ambigu: ${m.ambiguous.join(', ')}` : 'tidak ada nama POI yang cocok' }); continue; }
  if (byId.has(m.id)) { duplicates.push({ file, id: m.id, kept: byId.get(m.id) }); continue; }
  byId.set(m.id, file);
}

for (const [id, file] of byId) {
  const meta = await sharp(file).metadata();
  const { width: w, height: h } = meta;
  const focus = POI_PHOTO_CONFIG[id].focus;
  const box = cropBox(w, h, focus);
  for (const s of OUTPUT.sizes) {
    await sharp(file)
      .rotate()
      .extract(box)
      .resize(s.width, s.height, { fit: 'cover' })
      .webp({ quality: s.quality })
      .toFile(path.join(OUTPUT.dir, `${id}${s.suffix}.webp`));
  }
  matched.push({
    id, file, w, h, box,
    kept: (box.width * box.height) / (w * h),
    upscaled: box.width < OUTPUT.sizes[0].width,
    focus: focus ? `${focus.x ?? 0.5}, ${focus.y ?? 0.5}` : 'default',
  });
}

// Remove outputs for POIs that no longer have a source photo.
for (const f of fs.readdirSync(OUTPUT.dir)) {
  const id = f.replace(/(-sm)?\.webp$/, '');
  if (f.endsWith('.webp') && !byId.has(id)) fs.unlinkSync(path.join(OUTPUT.dir, f));
}

const ids = Object.keys(POI_CATALOG).filter((id) => byId.has(id));
fs.writeFileSync(
  'src/data/poiPhotos.js',
  `// GENERATED by scripts/process-poi-photos.mjs. Do not edit by hand; run \`npm run poi:photos\`.\n` +
    `// POI ids that have a processed photo in public/images/poi.\n` +
    `export const POI_PHOTO_IDS = ${JSON.stringify(ids, null, 2).replace(/"/g, "'")};\n`,
);

// ---- Report (not deployed) ----
const rel = (f) => f.replace(/\\/g, '/');
const missing = Object.keys(POI_CATALOG).filter((id) => !byId.has(id));
const heavy = matched.filter((m) => m.kept < HEAVY_CROP);
const lowRes = matched.filter((m) => m.upscaled);
const lines = [
  '# POI photo report',
  '',
  `Generated by \`npm run poi:photos\` on ${new Date().toISOString().slice(0, 10)}. Not deployed.`,
  `Output: \`${OUTPUT.dir}/<id>.webp\` (${OUTPUT.sizes.map((s) => `${s.width}x${s.height}`).join(' and ')}, 4:3). Originals in \`${SRC_DIR}/\` untouched.`,
  'Adjust a crop: set `focus` for that POI in `scripts/poi-photo-config.mjs` and run `npm run poi:photos` again.',
  '',
  `## Matched (${matched.length})`,
  '',
  '| POI | Source file | Original | Kept area | Focus |',
  '|---|---|---|---|---|',
  ...matched.map((m) => `| ${POI_CATALOG[m.id].name} (\`${m.id}\`) | \`${rel(m.file)}\` | ${m.w}x${m.h} | ${Math.round(m.kept * 100)}% | ${m.focus} |`),
  '',
  `## Unmatched files (${unmatched.length + duplicates.length})`,
  '',
  ...(unmatched.length + duplicates.length
    ? [
        ...unmatched.map((u) => `- \`${rel(u.file)}\`: ${u.reason}`),
        ...duplicates.map((d) => `- \`${rel(d.file)}\`: second photo for \`${d.id}\` (used \`${rel(d.kept)}\`)`),
      ]
    : ['None.']),
  '',
  `## POIs without a photo (${missing.length}) — standard placeholder shown`,
  '',
  ...(missing.length ? missing.map((id) => `- ${POI_CATALOG[id].name} (\`${id}\`)`) : ['None.']),
  '',
  `## Heavy crops (less than ${HEAVY_CROP * 100}% of the original kept) (${heavy.length})`,
  '',
  ...(heavy.length ? heavy.map((m) => `- ${POI_CATALOG[m.id].name}: ${Math.round(m.kept * 100)}% kept (${m.w}x${m.h}, portrait or very wide)`) : ['None.']),
  '',
  `## Low resolution (upscaled to ${OUTPUT.sizes[0].width}px wide, may look soft) (${lowRes.length})`,
  '',
  ...(lowRes.length ? lowRes.map((m) => `- ${POI_CATALOG[m.id].name}: crop is only ${m.box.width}x${m.box.height}px; a larger photo is recommended`) : ['None.']),
  '',
];
fs.mkdirSync(path.dirname(REPORT), { recursive: true });
fs.writeFileSync(REPORT, lines.join('\n'));

console.log(`POI photos: ${matched.length} processed, ${unmatched.length + duplicates.length} unmatched, ${missing.length} POIs without photo. Report: ${REPORT}`);
