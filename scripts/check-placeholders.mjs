// Lists every placeholder still left in src/data:
//   1. text placeholders  ("[ISI: ...]")
//   2. image placeholders (`src: null`, `photo: null`, image objects without src)
//   3. properties without a map pin
// Usage: npm run check:placeholders            (informational, exit 0)
//        npm run check:placeholders -- --strict (exit 1 if anything remains)
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const strict = process.argv.includes('--strict');
const dataDir = path.resolve('src/data');

const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) =>
    d.isDirectory() ? walk(path.join(dir, d.name)) : [path.join(dir, d.name)],
  );

// ---- 1. Source scan (file, line, text) ----
const rows = [];
for (const file of walk(dataDir).filter((f) => /\.(m?js|jsx|json)$/.test(f))) {
  const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/);
  lines.forEach((line, i) => {
    const rel = path.relative(process.cwd(), file).replace(/\\/g, '/');
    for (const m of line.matchAll(/\[ISI:[^\]]*\]/g)) rows.push({ file: rel, line: i + 1, text: m[0] });
    if (/\b(src|photo):\s*null\b/.test(line) && !line.trim().startsWith('//')) {
      rows.push({ file: rel, line: i + 1, text: line.trim().slice(0, 110) });
    }
  });
}

console.log('\n=== Placeholder di src/data (file:baris  teks) ===\n');
for (const r of rows) console.log(`${r.file}:${r.line}\t${r.text}`);
console.log(`\nTotal baris placeholder (teks + gambar): ${rows.length}`);

// ---- 2. Runtime summary per property (images are generated by helper functions) ----
const { PROPERTIES } = await import(pathToFileURL(path.join(dataDir, 'properties.js')).href);
const { BRAND } = await import(pathToFileURL(path.join(dataDir, 'brand.js')).href);
const missing = (imgs = []) => imgs.filter((i) => !i?.src).length;

console.log('\n=== Ringkasan foto & peta per properti ===\n');
let imageCount = missing(BRAND.heroPhotos);
let pinCount = 0;
if (imageCount) console.log(`Brand: foto hero belum ada: ${imageCount} dari ${BRAND.heroPhotos.length} (BRAND.heroPhotos)`);
if (!BRAND.logo) console.log('Brand: logo masih teks (BRAND.logo = null)');
for (const p of PROPERTIES) {
  const gallery = missing(p.gallery);
  const rooms = (p.roomTypes || []).reduce((n, r) => n + missing(r.photos), 0);
  const pois = (p.pois || []).filter((x) => !x.photo?.src).length;
  const pin = p.map ? 'pin OK' : p.status === 'open' ? 'TANPA PIN' : 'tanpa peta';
  imageCount += gallery + rooms + pois;
  if (p.status === 'open' && !p.map) pinCount += 1;
  console.log(
    `${p.name.padEnd(24)} galeri: ${gallery}  foto kamar: ${rooms}  foto POI: ${pois}  peta: ${pin}`,
  );
}

const textCount = rows.filter((r) => r.text.startsWith('[ISI:')).length;
console.log(`\nTeks [ISI: ...]: ${textCount} · Foto placeholder: ${imageCount} · Properti tanpa pin: ${pinCount}\n`);

if (strict && (textCount || imageCount || pinCount)) {
  console.error('STRICT: masih ada placeholder. Lengkapi sebelum launch.');
  process.exit(1);
}
